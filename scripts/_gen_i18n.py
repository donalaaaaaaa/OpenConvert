def xml_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def item(name: str, value: str) -> str:
    return f'    <string name="{name}">{xml_escape(value)}</string>'


def main() -> None:
    src = VALUES.read_text(encoding="utf-8")
    src = src.replace(
        '<string name="app_version_label">1.0.0 正式版</string>',
        '<string name="app_version_label">1.1.0</string>',
    )
    extra_block = "\n".join(item(n, zh) for n, zh, _ in EXTRA)
    if "name=\"quality_high\"" not in src:
        src = src.replace("</resources>", extra_block + "\n</resources>\n")
    VALUES.write_text(src, encoding="utf-8", newline="\n")

    # Parse all names now in default file
    import re

    names = re.findall(r'<string name="([^"]+)">', VALUES.read_text(encoding="utf-8"))
    extra_en = {n: en for n, _, en in EXTRA}
    missing = [n for n in names if n not in EXISTING_EN and n not in extra_en]
    if missing:
        raise SystemExit(f"missing English for: {missing}")

    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for name in names:
        en = EXISTING_EN.get(name) or extra_en[name]
        lines.append(item(name, en))
    lines.append("</resources>\n")
    VALUES_EN.parent.mkdir(parents=True, exist_ok=True)
    VALUES_EN.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"default extras={len(EXTRA)} values-en={len(names)}")


if __name__ == "__main__":
    main()
